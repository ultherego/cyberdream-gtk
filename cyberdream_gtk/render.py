"""Turning a Theme + Target into CSS text."""

from __future__ import annotations

import re
from pathlib import Path

from .palette import ROOT, Theme, ThemeError
from .targets import ALL, Target

TEMPLATES = Path(__file__).resolve().parent / "templates"
PLACEHOLDER_RE = re.compile(r"\{\{(.*?)\}\}", re.S)


def render_template(text: str, theme: Theme, source: str = "<template>") -> str:
    def substitute(match: re.Match[str]) -> str:
        try:
            return theme.eval(match[1]).css()
        except ThemeError as exc:
            line = text.count("\n", 0, match.start()) + 1
            raise ThemeError(f"{source}:{line}: {exc}") from None

    return PLACEHOLDER_RE.sub(substitute, text)


def render(theme: Theme, target: Target) -> str:
    parts = []
    if target.kind == "gtk-overlay":
        named = theme.named_colors(*target.named_sections)
        width = max(map(len, named))
        parts += [
            f"/* {theme.name} for {target.name}: an overlay on {target.base}.\n"
            f" * Accent: {theme.accent}.\n"
            " * GENERATED by cyberdream-gtk from palette.toml and roles.toml.\n"
            " * Do not edit; change the sources and rebuild. */\n",
            "/* Named colors */\n"
            + "".join(
                f"@define-color {key.ljust(width)} {color.css()};\n"
                for key, color in named.items()
            ),
        ]
    for name in target.templates:
        path = TEMPLATES / name
        parts.append(render_template(path.read_text(encoding="utf-8"), theme, name))
    return "\n".join(part.rstrip("\n") + "\n" for part in parts)


def build(theme: Theme, out_dir: Path | None = None) -> list[Path]:
    """Write every target under out_dir (default: <project>/build)."""
    out_dir = out_dir or ROOT / "build"
    written = []
    for target in ALL:
        path = out_dir / target.name / target.output
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(render(theme, target), encoding="utf-8")
        written.append(path)
    return written
